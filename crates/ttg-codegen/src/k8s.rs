/// Join documents into one multi-document YAML file under a comment header.
fn render_docs(header: &str, docs: &[J]) -> String {
    let mut out = String::from(header);
    for d in docs {
        out.push_str("---\n");
        out.push_str(&to_yaml(d));
    }
    out
}

/// `render.sh`: bash 3.2 or later (macOS's), no jq and no envsubst — each token is read
/// with `<tool> output -raw` and substituted with bash's own string replacement.
fn render_sh(tokens: &[String], profile: Profile) -> String {
    let mut s = format!(
        "#!/usr/bin/env bash\n\
         # Generated by TerraTofu GUI. Copies the manifests next to this script into\n\
         # ./rendered/, replacing every ${{k8s_...}} token with the Terraform output of the\n\
         # same name. Run it after `{bin} apply`.\n\
         #\n\
         #   TF      the binary to read outputs with (default: {bin})\n\
         #   TF_DIR  the configuration directory (default: the parent of this one)\n\
         set -euo pipefail\n\
         shopt -u patsub_replacement 2>/dev/null || true\n\
         here=\"$(cd \"$(dirname \"$0\")\" && pwd)\"\n\
         tf=\"${{TF:-{bin}}}\"\n\
         root=\"${{TF_DIR:-$here/..}}\"\n\
         out=\"$here/rendered\"\n\
         names=(\n",
        bin = profile.binary()
    );
    for t in tokens {
        s.push_str(&format!("  {t}\n"));
    }
    s.push_str(
        ")\n\
         values=()\n\
         for n in ${names[@]+\"${names[@]}\"}; do\n\
         \x20 if ! v=\"$(\"$tf\" -chdir=\"$root\" output -raw \"$n\")\"; then\n\
         \x20   echo \"render.sh: no output '$n' in $root; run '$tf apply' first\" >&2\n\
         \x20   exit 1\n\
         \x20 fi\n\
         \x20 # The tokens sit inside double-quoted YAML strings.\n\
         \x20 v=${v//\\\\/\\\\\\\\}\n\
         \x20 v=${v//\\\"/\\\\\\\"}\n\
         \x20 values+=(\"$v\")\n\
         done\n\
         mkdir -p \"$out\"\n\
         count=0\n\
         for f in \"$here\"/*.yaml; do\n\
         \x20 [ -e \"$f\" ] || continue\n\
         \x20 content=\"$(cat \"$f\"; printf x)\"\n\
         \x20 content=${content%x}\n\
         \x20 i=0\n\
         \x20 for n in ${names[@]+\"${names[@]}\"}; do\n\
         \x20   pattern=\"\\${$n}\"\n\
         \x20   content=${content//\"$pattern\"/${values[$i]}}\n\
         \x20   i=$((i + 1))\n\
         \x20 done\n\
         \x20 printf '%s' \"$content\" > \"$out/$(basename \"$f\")\"\n\
         \x20 count=$((count + 1))\n\
         done\n\
         echo \"rendered $count file(s) into $out; apply them with: kubectl apply -f $out\"\n",
    );
    s
}

/// `render.ps1`: Windows PowerShell 5.1 or PowerShell 7; `<tool> output -json` is parsed
/// natively.
fn render_ps1(tokens: &[String], profile: Profile) -> String {
    let mut s = format!(
        "# Generated by TerraTofu GUI. Copies the manifests next to this script into\n\
         # .\\rendered\\, replacing every ${{k8s_...}} token with the Terraform output of the\n\
         # same name. Run it after `{bin} apply`.\n\
         param(\n\
         \x20   [string]$Tool = \"{bin}\",\n\
         \x20   [string]$Dir = (Join-Path $PSScriptRoot \"..\")\n\
         )\n\
         $ErrorActionPreference = \"Stop\"\n\
         $names = @(\n",
        bin = profile.binary()
    );
    let quoted: Vec<String> = tokens.iter().map(|t| format!("    \"{t}\"")).collect();
    s.push_str(&quoted.join(",\n"));
    if !quoted.is_empty() {
        s.push('\n');
    }
    s.push_str(
        ")\n\
         $json = (& $Tool \"-chdir=$Dir\" output -json) | Out-String\n\
         if ($LASTEXITCODE -ne 0) { throw \"'$Tool output' failed in $Dir; run '$Tool apply' first\" }\n\
         $outputs = $json | ConvertFrom-Json\n\
         $values = @{}\n\
         foreach ($n in $names) {\n\
         \x20   $o = $outputs.PSObject.Properties[$n]\n\
         \x20   if ($null -eq $o) { throw \"render.ps1: no output '$n' in $Dir; run '$Tool apply' first\" }\n\
         \x20   # The tokens sit inside double-quoted YAML strings.\n\
         \x20   $values[$n] = ([string]$o.Value.value).Replace('\\', '\\\\').Replace('\"', '\\\"')\n\
         }\n\
         $out = Join-Path $PSScriptRoot \"rendered\"\n\
         New-Item -ItemType Directory -Force -Path $out | Out-Null\n\
         $count = 0\n\
         foreach ($f in Get-ChildItem -Path $PSScriptRoot -Filter *.yaml) {\n\
         \x20   $text = [System.IO.File]::ReadAllText($f.FullName)\n\
         \x20   foreach ($n in $names) { $text = $text.Replace('${' + $n + '}', $values[$n]) }\n\
         \x20   [System.IO.File]::WriteAllText((Join-Path $out $f.Name), $text)\n\
         \x20   $count++\n\
         }\n\
         Write-Output \"rendered $count file(s) into $out; apply them with: kubectl apply -f $out\"\n",
    );
    s
}

