/// Render a JSON value as block-style YAML. Strings are written plain only when they
/// cannot be read back as anything else (no YAML 1.1 booleans, numbers, `${…}` tokens or
/// punctuation); everything else is a JSON-escaped double-quoted scalar, which YAML reads
/// as the same string. Maps keep their insertion order.
pub fn to_yaml(v: &J) -> String {
    let mut out = String::new();
    match v {
        J::Object(m) if !m.is_empty() => write_map(&mut out, m, 0),
        J::Array(a) if !a.is_empty() => write_list(&mut out, a, 0),
        other => {
            out.push_str(&scalar(other));
            out.push('\n');
        }
    }
    out
}

fn write_map(out: &mut String, m: &Map<String, J>, indent: usize) {
    let pad = " ".repeat(indent);
    for (k, v) in m {
        out.push_str(&format!("{pad}{}:", scalar_str(k)));
        write_value(out, v, indent);
    }
}

/// The part after `key:` — a scalar on the same line, or a nested block below it.
fn write_value(out: &mut String, v: &J, indent: usize) {
    match v {
        J::Object(inner) if !inner.is_empty() => {
            out.push('\n');
            write_map(out, inner, indent + 2);
        }
        J::Array(items) if !items.is_empty() => {
            out.push('\n');
            write_list(out, items, indent + 2);
        }
        other => {
            out.push(' ');
            out.push_str(&scalar(other));
            out.push('\n');
        }
    }
}

fn write_list(out: &mut String, items: &[J], indent: usize) {
    let pad = " ".repeat(indent);
    for item in items {
        match item {
            // A map item starts on the dash line: write it one level deeper, then swap
            // the first line's indentation for the dash.
            J::Object(m) if !m.is_empty() => {
                let mut block = String::new();
                write_map(&mut block, m, indent + 2);
                out.push_str(&pad);
                out.push_str("- ");
                out.push_str(&block[indent + 2..]);
            }
            J::Array(inner) if !inner.is_empty() => {
                out.push_str(&format!("{pad}-\n"));
                write_list(out, inner, indent + 2);
            }
            other => out.push_str(&format!("{pad}- {}\n", scalar(other))),
        }
    }
}

fn scalar(v: &J) -> String {
    match v {
        J::Null => "null".into(),
        J::Bool(b) => b.to_string(),
        J::Number(n) => n.to_string(),
        J::String(s) => scalar_str(s),
        J::Object(_) => "{}".into(),
        J::Array(_) => "[]".into(),
    }
}

fn scalar_str(s: &str) -> String {
    let plain = s.chars().next().is_some_and(|c| c.is_ascii_alphabetic())
        && s.chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.' | '/'))
        && !matches!(
            s.to_ascii_lowercase().as_str(),
            "y" | "n" | "yes" | "no" | "true" | "false" | "on" | "off" | "null"
        );
    if plain {
        s.to_string()
    } else {
        serde_json::to_string(s).expect("a string always serialises")
    }
}

/// Replace every `${name}` token in `text` with its value, escaped for the double-quoted
/// YAML string it sits in — what the render scripts do, for tests and previews.
pub fn render_tokens(text: &str, values: &IndexMap<String, String>) -> String {
    let mut out = text.to_string();
    for (name, value) in values {
        let escaped = value.replace('\\', "\\\\").replace('"', "\\\"");
        out = out.replace(&format!("${{{name}}}"), &escaped);
    }
    out
}

/// The `${…}` token names a manifest file contains, in order of first appearance. Only
/// output names count (letters, digits, `_`), so the header's `${k8s_...}` does not.
pub fn tokens_in(text: &str) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    let mut rest = text;
    while let Some(i) = rest.find("${") {
        let after = &rest[i + 2..];
        let Some(end) = after.find('}') else { break };
        let name = &after[..end];
        let valid = !name.is_empty() && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
        if valid && !out.iter().any(|x| x == name) {
            out.push(name.to_string());
        }
        rest = &after[end + 1..];
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn yaml_quotes_what_would_read_back_differently() {
        let v = json!({
            "apiVersion": "v1",
            "kind": "ConfigMap",
            "metadata": { "name": "x", "labels": { "app.kubernetes.io/name": "x" } },
            "data": {
                "on": "yes",
                "port": "8080",
                "token": "${k8s_jobs_url}",
                "empty": "",
                "json": "{\"a\":1}",
            },
            "list": [ { "name": "a", "value": "b" }, "plain", 3, [ "nested" ] ],
            "none": [],
            "obj": {},
        });
        let y = to_yaml(&v);
        assert_eq!(
            y,
            "apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: x\n  labels:\n    app.kubernetes.io/name: x\n\
             data:\n  \"on\": \"yes\"\n  port: \"8080\"\n  token: \"${k8s_jobs_url}\"\n  empty: \"\"\n  json: \"{\\\"a\\\":1}\"\n\
             list:\n  - name: a\n    value: b\n  - plain\n  - 3\n  -\n    - nested\nnone: []\nobj: {}\n"
        );
    }

    #[test]
    fn tokens_are_found_and_rendered_escaped() {
        let text = "a: \"${k8s_a}\"\nb: \"${k8s_b}/x:${k8s_a}\"\n";
        assert_eq!(tokens_in(text), vec!["k8s_a", "k8s_b"]);
        let mut values = IndexMap::new();
        values.insert("k8s_a".to_string(), "q\"\\".to_string());
        values.insert("k8s_b".to_string(), "host".to_string());
        assert_eq!(
            render_tokens(text, &values),
            "a: \"q\\\"\\\\\"\nb: \"host/x:q\\\"\\\\\"\n"
        );
    }

    #[test]
    fn names() {
        assert_eq!(k8s_name("ASR Worker"), "asr-worker");
        assert_eq!(env_part("api key"), "API_KEY");
        assert_eq!(env_part("core db"), "CORE_DB");
    }
}
