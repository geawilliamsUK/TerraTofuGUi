pub fn backend_kind(kind: &str) -> Option<&'static BackendKind> {
    BACKENDS.iter().find(|b| b.kind == kind)
}

impl BackendKind {
    /// Every key this backend takes, required first.
    pub fn keys(&self) -> impl Iterator<Item = &'static str> + '_ {
        self.required.iter().chain(self.optional).map(|(k, _)| *k)
    }
    pub fn help(&self, key: &str) -> &'static str {
        self.required
            .iter()
            .chain(self.optional)
            .find(|(k, _)| *k == key)
            .map(|(_, h)| *h)
            .unwrap_or("")
    }
}

/// A copy with blank values dropped: an empty text box in the settings panel means "not
/// set", never "set to the empty string".
pub fn normalized(cfg: &BackendConfig) -> BackendConfig {
    BackendConfig {
        backend_type: cfg.backend_type.trim().to_string(),
        args: cfg
            .args
            .iter()
            .filter(|(_, v)| !v.trim().is_empty())
            .map(|(k, v)| (k.trim().to_string(), v.trim().to_string()))
            .collect(),
    }
}

/// Check a backend configuration: a known type, only that type's keys, every required
/// key set. The message names what is wrong and what would be right.
pub fn check_backend(cfg: &BackendConfig) -> Result<(), String> {
    let cfg = normalized(cfg);
    let Some(kind) = backend_kind(&cfg.backend_type) else {
        return Err(format!(
            "unknown backend type \"{}\"; use one of: {}",
            cfg.backend_type,
            BACKENDS.iter().map(|b| b.kind).collect::<Vec<_>>().join(", ")
        ));
    };
    let valid: Vec<&str> = kind.keys().collect();
    for k in cfg.args.keys() {
        if !valid.contains(&k.as_str()) {
            return Err(format!(
                "the {} backend takes {}; \"{k}\" is not one of them",
                kind.kind,
                valid.join(", ")
            ));
        }
    }
    for other in ["key", "prefix"] {
        if cfg.args.contains_key("key_prefix") && cfg.args.contains_key(other) {
            return Err(format!(
                "set key_prefix or {other}, not both: they say the same thing (the state object is <key_prefix>/terraform.tfstate)"
            ));
        }
    }
    let missing: Vec<&str> = kind
        .required
        .iter()
        .map(|(k, _)| *k)
        .filter(|k| !cfg.args.contains_key(*k))
        .collect();
    if !missing.is_empty() {
        return Err(format!(
            "the {} backend needs {}; missing: {}",
            kind.kind,
            kind.required
                .iter()
                .map(|(k, _)| *k)
                .collect::<Vec<_>>()
                .join(", "),
            missing.join(", ")
        ));
    }
    let prefix = ["key_prefix", "prefix", "key"]
        .iter()
        .find_map(|k| cfg.args.get(*k).map(|v| (*k, v)));
    if let Some((which, prefix)) = prefix {
        if prefix.starts_with('/')
            || prefix.ends_with('/')
            || prefix.split('/').any(|s| s.is_empty() || s == "." || s == "..")
            || prefix.chars().any(char::is_whitespace)
        {
            return Err(format!(
                "{which} \"{prefix}\" must be a relative path like `team/app`: no leading or trailing slash, no empty, `.` or `..` segments, no spaces"
            ));
        }
    }
    Ok(())
}

/// Read the `backend` argument of `settings_set`: `null` (or `{"type": "none"}`) clears
/// it; otherwise `{"type": "s3", "bucket": "…", "region": "…"}`, or the `{type, args}`
/// shape `project_get` returns. The result has passed [`check_backend`].
pub fn backend_from_json(v: &serde_json::Value) -> Result<Option<BackendConfig>, String> {
    use serde_json::Value as J;
    let obj = match v {
        J::Null => return Ok(None),
        J::Object(o) => o,
        _ => return Err("backend must be an object like {\"type\": \"s3\", \"bucket\": \"…\", \"region\": \"…\"}, or null".into()),
    };
    let kind = match obj.get("type") {
        Some(J::String(s)) => s.trim().to_string(),
        _ => {
            return Err(format!(
                "backend needs a \"type\": one of {}",
                BACKENDS.iter().map(|b| b.kind).collect::<Vec<_>>().join(", ")
            ))
        }
    };
    if kind == "none" {
        return Ok(None);
    }
    let text = |k: &str, v: &J| -> Result<String, String> {
        match v {
            J::String(s) => Ok(s.clone()),
            J::Number(n) => Ok(n.to_string()),
            _ => Err(format!("backend.{k} must be a string")),
        }
    };
    let mut args = BTreeMap::new();
    for (k, v) in obj {
        match k.as_str() {
            "type" => {}
            "args" => {
                let J::Object(inner) = v else {
                    return Err("backend.args must be an object".into());
                };
                for (ik, iv) in inner {
                    args.insert(ik.clone(), text(ik, iv)?);
                }
            }
            _ => {
                args.insert(k.clone(), text(k, v)?);
            }
        }
    }
    let cfg = normalized(&BackendConfig {
        backend_type: kind,
        args,
    });
    check_backend(&cfg)?;
    Ok(Some(cfg))
}

/// The folder the state is kept under: `<key_prefix>` (the `gcs` backend's own
/// `prefix` is accepted for it; default: the project name in kebab case), then the
/// environment when there is one. Named environments are a later package; every caller
/// passes `None` today, and the key already has room for one:
/// `<key_prefix>/<environment>/terraform.tfstate`.
pub fn state_prefix(p: &Project, cfg: &BackendConfig, environment: Option<&str>) -> String {
    let base = ["key_prefix", "prefix"]
        .iter()
        .find_map(|k| cfg.args.get(*k))
        .map(|s| s.trim().to_string())
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| kebab(&p.name));
    match env_segment(environment) {
        Some(env) => format!("{base}/{env}"),
        None => base,
    }
}

fn env_segment(environment: Option<&str>) -> Option<String> {
    environment.map(str::trim).filter(|e| !e.is_empty()).map(kebab)
}

/// The state object's key for the `s3` and `azurerm` backends:
/// `<key_prefix>[/<environment>]/terraform.tfstate`, or an explicit `key` with the
/// environment put in front of its file name.
pub fn state_key(p: &Project, cfg: &BackendConfig, environment: Option<&str>) -> String {
    if let Some(key) = cfg.args.get("key").map(|k| k.trim()).filter(|k| !k.is_empty()) {
        return match (env_segment(environment), key.rsplit_once('/')) {
            (None, _) => key.to_string(),
            (Some(env), Some((dir, file))) => format!("{dir}/{env}/{file}"),
            (Some(env), None) => format!("{env}/{key}"),
        };
    }
    format!("{}/terraform.tfstate", state_prefix(p, cfg, environment))
}

fn kebab(s: &str) -> String {
    ttg_core::slugify(s).replace('_', "-")
}

/// `backend "<type>" { … }`, every argument a literal: a backend block cannot use
/// variables (the backend is configured before anything is evaluated).
pub fn backend_block(p: &Project, cfg: &BackendConfig, environment: Option<&str>) -> Block {
    let cfg = normalized(cfg);
    let arg = |k: &str| cfg.args.get(k).cloned().unwrap_or_default();
    let b = Block::builder("backend").add_label(cfg.backend_type.as_str());
    let b = match cfg.backend_type.as_str() {
        "s3" => {
            let mut b = b
                .add_attribute(("bucket", arg("bucket")))
                .add_attribute(("key", state_key(p, &cfg, environment)))
                .add_attribute(("region", arg("region")))
                .add_attribute(("encrypt", true))
                // S3 conditional writes: no DynamoDB lock table (OpenTofu 1.10+, Terraform 1.11+).
                .add_attribute(("use_lockfile", true));
            if let Some(k) = cfg.args.get("kms_key_id") {
                b = b.add_attribute(("kms_key_id", k.as_str()));
            }
            b
        }
        "azurerm" => b
            .add_attribute(("resource_group_name", arg("resource_group_name")))
            .add_attribute(("storage_account_name", arg("storage_account_name")))
            .add_attribute(("container_name", arg("container_name")))
            .add_attribute(("key", state_key(p, &cfg, environment))),
        "gcs" => b
            .add_attribute(("bucket", arg("bucket")))
            .add_attribute(("prefix", state_prefix(p, &cfg, environment))),
        _ => {
            let mut b = b;
            if let Some(path) = cfg.args.get("path") {
                b = b.add_attribute(("path", path.as_str()));
            }
            b
        }
    };
    b.build()
}

/// The backend the export writes, if the settings hold a valid one.
pub fn configured_backend(p: &Project) -> Option<BackendConfig> {
    let cfg = normalized(p.settings.backend.as_ref()?);
    check_backend(&cfg).ok().map(|_| cfg)
}

/// A remote backend with a store for the bootstrap root to create (`local` has none).
fn remote_backend(p: &Project) -> Option<(BackendConfig, &'static BackendKind)> {
    let cfg = configured_backend(p)?;
    let kind = backend_kind(&cfg.backend_type)?;
    kind.provider.map(|_| (cfg, kind))
}

// ------------------------------------------------------------------ encryption

/// Which OpenTofu key provider protects the state.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum KeySource {
    /// `aws_kms`: an AWS KMS key generates the data keys.
    AwsKms,
    /// `gcp_kms`: a Cloud KMS crypto key wraps them.
    GcpKms,
    /// `pbkdf2`: a key derived from a passphrase variable (`state_passphrase`).
    Passphrase,
}

/// The effective state encryption for one provider's export.
#[derive(Debug, Clone)]
pub struct EncryptionPlan {
    pub source: KeySource,
    /// The `encryption_key` entity a KMS key provider uses.
    pub key: Option<Id>,
    /// The key is created by the bootstrap root (it is not flagged external).
    pub key_in_bootstrap: bool,
    /// AWS: the region the key lives in (the bootstrap root's region).
    pub region: Option<String>,
}

impl EncryptionPlan {
    /// The attribute of the key the key provider takes: its ARN on AWS, its full id
    /// (`projects/…/cryptoKeys/…`) on Google Cloud.
    pub fn key_attr(&self) -> Option<&'static str> {
        match self.source {
            KeySource::AwsKms => Some("arn"),
            KeySource::GcpKms => Some("id"),
            KeySource::Passphrase => None,
        }
    }
}

/// The entity `state_encryption_key` names, if it exists and is an Encryption Key.
pub fn state_key_entity(p: &Project) -> Option<Id> {
    let id = p.settings.state_encryption_key.as_deref()?;
    let e = p.entity(id)?;
    (e.resource_type == "encryption_key").then(|| e.id.to_string())
}

/// The AWS region the bootstrap root creates things in: the S3 backend's region when
/// the state is kept in S3 (the bucket must be there), else the project's AWS region.
pub fn aws_bootstrap_region(p: &Project, cat: &Catalog) -> String {
    if let Some(cfg) = configured_backend(p).filter(|c| c.backend_type == "s3") {
        if let Some(r) = cfg.args.get("region") {
            return r.clone();
        }
    }
    aws_region(p, cat)
}

fn aws_region(p: &Project, cat: &Catalog) -> String {
    p.settings
        .provider_settings
        .get("aws")
        .and_then(|m| m.get("region"))
        .filter(|s| !s.trim().is_empty())
        .cloned()
        .or_else(|| {
            cat.provider("aws")?
                .variables
                .iter()
                .find(|v| v.name == "region")?
                .default
                .as_ref()?
                .as_str()
                .map(str::to_string)
        })
        .unwrap_or_default()
}

/// The state encryption `layer` (one provider's layer of the project) gets, or `None`
/// when there is none: encryption off, or the tool is Terraform, which has no
/// `encryption` block.
pub fn encryption_plan(layer: &Project, cat: &Catalog, provider: &str, tool: Tool) -> Option<EncryptionPlan> {
    if !layer.settings.state_encryption || !crate::tool::Profile::new(tool).supports_state_encryption() {
        return None;
    }
    let key = state_key_entity(layer);
    let source = match (provider, &key) {
        ("aws", Some(_)) => KeySource::AwsKms,
        ("gcp", Some(_)) => KeySource::GcpKms,
        _ => KeySource::Passphrase,
    };
    if source == KeySource::Passphrase {
        return Some(EncryptionPlan {
            source,
            key: None,
            key_in_bootstrap: false,
            region: None,
        });
    }
    let key = key.unwrap();
    let manual = layer.entity(&key).is_some_and(|e| e.manual);
    Some(EncryptionPlan {
        source,
        key_in_bootstrap: !manual,
        region: (source == KeySource::AwsKms).then(|| aws_bootstrap_region(layer, cat)),
        key: Some(key),
    })
}

/// The name the key provider and method are declared under.
const ENC_NAME: &str = "state";

/// `encryption { key_provider … method … state { … } plan { … } }` (OpenTofu 1.7+).
/// `key` is the expression the KMS key provider takes (the key's ARN or id, a variable
/// in practice: the key lives in the bootstrap root).
pub fn encryption_block(plan: &EncryptionPlan, key: Option<Expression>) -> Block {
    let (kp_type, kp) = match plan.source {
        KeySource::AwsKms => (
            "aws_kms",
            Block::builder("key_provider")
                .add_label("aws_kms")
                .add_label(ENC_NAME)
                .add_attribute(("kms_key_id", key.unwrap_or(Expression::Null)))
                .add_attribute(("region", plan.region.clone().unwrap_or_default()))
                .add_attribute(("key_spec", "AES_256"))
                .build(),
        ),
        KeySource::GcpKms => (
            "gcp_kms",
            Block::builder("key_provider")
                .add_label("gcp_kms")
                .add_label(ENC_NAME)
                .add_attribute(("kms_encryption_key", key.unwrap_or(Expression::Null)))
                .add_attribute(("key_length", 32))
                .build(),
        ),
        KeySource::Passphrase => (
            "pbkdf2",
            Block::builder("key_provider")
                .add_label("pbkdf2")
                .add_label(ENC_NAME)
                .add_attribute(("passphrase", traversal(&["var", PASSPHRASE_VAR])))
                .build(),
        ),
    };
    let method = Block::builder("method")
        .add_label("aes_gcm")
        .add_label(ENC_NAME)
        .add_attribute(("keys", traversal(&["key_provider", kp_type, ENC_NAME])))
        .build();
    // `enforced`: refuse to read or write an unencrypted state or plan, so a missing
    // key fails loudly instead of silently writing plain text.
    let target = |name: &str| {
        Block::builder(name)
            .add_attribute(("method", traversal(&["method", "aes_gcm", ENC_NAME])))
            .add_attribute(("enforced", true))
            .build()
    };
    Block::builder("encryption")
        .add_block(kp)
        .add_block(method)
        .add_block(target("state"))
        .add_block(target("plan"))
        .build()
}

/// The variable a passphrase key provider reads.
pub const PASSPHRASE_VAR: &str = "state_passphrase";

fn traversal(parts: &[&str]) -> Expression {
    let mut t = Traversal::builder(Variable::unchecked(parts[0]));
    for p in &parts[1..] {
        t = t.attr(*p);
    }
    Expression::Traversal(Box::new(t.build()))
}

/// The lowest tool version the `terraform {}` block's state features need, if any is
/// above the profile's floor: S3 lock files (`use_lockfile`) arrived in OpenTofu 1.10
/// and Terraform 1.11, state encryption in OpenTofu 1.7.
pub fn required_version(p: &Project, tool: Tool, encrypted: bool) -> Option<&'static str> {
    let s3 = configured_backend(p).is_some_and(|c| c.backend_type == "s3");
    match tool {
        Tool::OpenTofu if s3 => Some(">= 1.10.0"),
        Tool::OpenTofu if encrypted => Some(">= 1.7.0"),
        Tool::Terraform if s3 => Some(">= 1.11.0"),
        _ => None,
    }
}

