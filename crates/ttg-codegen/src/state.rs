/// Directory (inside the export) of the bootstrap root.
pub const BOOTSTRAP_DIR: &str = "bootstrap";

/// Id of the state bucket in a bootstrap project.
pub const STORE_ID: &str = "tfstate-store";
const STORE_RG_ID: &str = "tfstate-rg";

/// One separate root the export writes under `bootstrap/`: a small project of its own
/// and the provider it is generated for.
#[derive(Debug, Clone)]
pub struct BootstrapRoot {
    /// Path inside the export: `bootstrap`, or `bootstrap/<provider>` for a second root
    /// when the state store and the state key are on different clouds.
    pub dir: String,
    pub provider: String,
    pub project: Project,
    /// The state key's id when this root creates it.
    pub key: Option<Id>,
    /// This root creates the backend's store.
    pub store: bool,
}

/// The bootstrap roots one provider's export gets: the remote backend's store, and the
/// state key when a KMS key provider uses one (the key must exist before the state it
/// encrypts, so it cannot be part of the configuration whose state that is). One root
/// when both are on the same cloud; two when they are not (an S3 backend for the Google
/// Cloud export encrypted with a Cloud KMS key). Empty when there is nothing to create.
pub fn bootstrap_roots(layer: &Project, cat: &Catalog, provider: &str, tool: Tool) -> Vec<BootstrapRoot> {
    let store = remote_backend(layer);
    let key = encryption_plan(layer, cat, provider, tool)
        .filter(|e| e.key_in_bootstrap)
        .and_then(|e| e.key);
    let mut roots: Vec<BootstrapRoot> = Vec::new();
    if let Some((cfg, kind)) = &store {
        let pid = kind.provider.unwrap();
        let mut mini = bootstrap_project(layer, pid, cat);
        add_store(&mut mini, layer, cfg, cat);
        roots.push(BootstrapRoot {
            dir: BOOTSTRAP_DIR.into(),
            provider: pid.into(),
            project: mini,
            key: None,
            store: true,
        });
    }
    if let Some(key) = key {
        match roots.iter_mut().find(|r| r.provider == provider) {
            Some(r) => {
                add_key(&mut r.project, layer, &key);
                r.key = Some(key);
            }
            None => {
                let mut mini = bootstrap_project(layer, provider, cat);
                add_key(&mut mini, layer, &key);
                let dir = if roots.is_empty() {
                    BOOTSTRAP_DIR.to_string()
                } else {
                    format!("{BOOTSTRAP_DIR}/{provider}")
                };
                roots.push(BootstrapRoot {
                    dir,
                    provider: provider.into(),
                    project: mini,
                    key: Some(key),
                    store: false,
                });
            }
        }
    }
    roots
}

/// An empty project with the main project's settings minus everything about state: the
/// bootstrap root keeps its own (small, secret-free) state locally.
fn bootstrap_project(main: &Project, provider: &str, cat: &Catalog) -> Project {
    let mut p = Project::new(&format!("{} state bootstrap", main.name));
    p.settings.tool = main.settings.tool;
    p.settings.target_provider = provider.to_string();
    p.settings.provider_settings = main.settings.provider_settings.clone();
    p.settings.tags = main.settings.tags.clone();
    p.settings.provider_versions = main.settings.provider_versions.clone();
    if provider == "aws" {
        // The S3 bucket must be where the backend looks for it, and the key goes with it.
        let region = aws_bootstrap_region(main, cat);
        if !region.is_empty() {
            p.settings
                .provider_settings
                .entry("aws".into())
                .or_default()
                .insert("region".into(), region);
        }
    }
    p
}

/// The field defaults a node dropped on the canvas starts with, abstract and per
/// provider: a mapping reads a provider field's value, not its declared default.
fn defaults(cat: &Catalog, resource_type: &str) -> (Config, BTreeMap<String, Config>) {
    let mut config = Config::new();
    let mut provider_config = BTreeMap::new();
    if let Some(def) = cat.resource(resource_type) {
        for f in &def.fields {
            if let Some(v) = f.default_value() {
                config.insert(f.name.clone(), v);
            }
        }
        for (pid, m) in &def.providers {
            let c: Config = m
                .fields
                .iter()
                .filter_map(|f| f.default_value().map(|v| (f.name.clone(), v)))
                .collect();
            provider_config.insert(pid.clone(), c);
        }
    }
    (config, provider_config)
}

fn node(cat: &Catalog, id: &str, name: &str, resource_type: &str) -> Node {
    let (config, provider_config) = defaults(cat, resource_type);
    Node {
        id: id.into(),
        name: name.into(),
        resource_type: resource_type.into(),
        config,
        provider_config,
        position: Default::default(),
        size: None,
        parent: None,
        manual: false,
        providers: Vec::new(),
        extra: Default::default(),
        classification: None,
        description: String::new(),
        owner: String::new(),
    }
}

/// The state bucket: an Object Storage node with versioning on, public access blocked
/// and plain HTTP refused, named exactly as the backend expects.
fn add_store(mini: &mut Project, main: &Project, cfg: &BackendConfig, cat: &Catalog) {
    let arg = |k: &str| Value::Str(cfg.args.get(k).cloned().unwrap_or_default());
    let mut n = node(cat, STORE_ID, &format!("{} state", main.name), "object_storage");
    n.config.insert("versioning".into(), Value::Bool(true));
    n.config.insert("block_public_access".into(), Value::Bool(true));
    n.config.insert("tls_only".into(), Value::Bool(true));
    match cfg.backend_type.as_str() {
        "s3" => {
            n.provider_config
                .entry("aws".into())
                .or_default()
                .insert("bucket_name".into(), arg("bucket"));
        }
        "gcs" => {
            n.provider_config
                .entry("gcp".into())
                .or_default()
                .insert("bucket_name".into(), arg("bucket"));
        }
        "azurerm" => {
            let azure = n.provider_config.entry("azure".into()).or_default();
            azure.insert("account_name".into(), arg("storage_account_name"));
            azure.insert("container_name".into(), arg("container_name"));
            // The resource group's mapping kebab-cases the display name; the backend
            // needs the exact name, so it is set as an extra argument (which wins).
            let rg_name = cfg.args.get("resource_group_name").cloned().unwrap_or_default();
            let mut extra = serde_json::Map::new();
            extra.insert("name".into(), serde_json::Value::String(rg_name.clone()));
            let (config, provider_config) = defaults(cat, "resource_group");
            let rg = Container {
                id: STORE_RG_ID.into(),
                name: rg_name,
                container_type: "resource_group".into(),
                config,
                provider_config,
                position: Default::default(),
                size: Default::default(),
                parent: None,
                manual: false,
                providers: Vec::new(),
                extra: [(
                    "azure".to_string(),
                    [("main".to_string(), extra)].into_iter().collect(),
                )]
                .into_iter()
                .collect(),
                classification: None,
                description: String::new(),
                owner: String::new(),
            };
            mini.containers.insert(rg.id.clone(), rg);
            n.parent = Some(STORE_RG_ID.into());
        }
        _ => {}
    }
    mini.nodes.insert(n.id.clone(), n);
}

/// The state key: the project's own Encryption Key entity, copied with its settings, so
/// it is generated by its own mapping (key policy included) in the bootstrap root.
fn add_key(mini: &mut Project, main: &Project, key: &str) {
    let Some(src) = main.nodes.get(key) else {
        return;
    };
    let mut n = src.clone();
    n.parent = None;
    n.providers.clear();
    mini.nodes.insert(n.id.clone(), n);
}

// ------------------------------------------------------------------ diagnostics

fn diag(entity: Option<&str>, severity: Severity, message: String) -> Diagnostic {
    Diagnostic {
        entity: entity.map(str::to_string),
        severity,
        code: Code::State,
        message,
        provider: None,
    }
}

/// Everything about state for one provider's export: the backend and the key setting
/// are valid, what Terraform cannot do, what the bootstrap root would refuse, and where a
/// secret the configuration generates ends up. `full` is the whole project, `layer` the
/// provider's layer of it.
pub fn checks(full: &Project, layer: &Project, cat: &Catalog, provider: &str, tool: Tool) -> Vec<Diagnostic> {
    let mut out = Vec::new();
    let s = &full.settings;
    let pname = cat
        .provider(provider)
        .map(|d| d.provider.display_name.clone())
        .unwrap_or(provider.to_string());

    // The backend.
    let backend = match &s.backend {
        None => None,
        Some(b) => match check_backend(b) {
            Ok(()) => Some(normalized(b)),
            Err(e) => {
                out.push(diag(
                    None,
                    Severity::Error,
                    format!("State backend: {e} (Settings ▸ State backend)"),
                ));
                None
            }
        },
    };
    let remote = backend.as_ref().filter(|b| b.backend_type != "local");
    if let Some(b) = remote {
        let kind = backend_kind(&b.backend_type).unwrap();
        if kind.provider.is_some_and(|bp| bp != provider) {
            let store = kind
                .provider
                .and_then(|bp| cat.provider(bp))
                .map(|d| d.provider.display_name.clone())
                .unwrap_or_default();
            out.push(diag(
                None,
                Severity::Info,
                format!(
                    "the {pname} export keeps its state in {} (backend \"{}\"): init and apply need {store} credentials as well, and its bootstrap root creates the store on {store}",
                    kind.display, b.backend_type
                ),
            ));
        }
    }

    // The key setting.
    let key = match s.state_encryption_key.as_deref() {
        None => None,
        Some(k) => {
            match full.entity(k) {
                Some(e) if e.resource_type == "encryption_key" => Some(e),
                Some(e) => {
                    let sev = if s.state_encryption && tool == Tool::OpenTofu {
                        Severity::Error
                    } else {
                        Severity::Warning
                    };
                    out.push(diag(
                    Some(e.id),
                    sev,
                    format!(
                        "the state encryption key \"{}\" is a {}, not an Encryption Key (Settings ▸ State encryption key)",
                        e.name, e.resource_type
                    ),
                ));
                    None
                }
                None => {
                    let sev = if s.state_encryption && tool == Tool::OpenTofu {
                        Severity::Error
                    } else {
                        Severity::Warning
                    };
                    out.push(diag(
                    None,
                    sev,
                    format!("the state encryption key \"{k}\" does not exist (Settings ▸ State encryption key)"),
                ));
                    None
                }
            }
        }
    };
    if key.is_some() && !s.state_encryption {
        out.push(diag(
            key.map(|k| k.id),
            Severity::Info,
            "is chosen as the state encryption key, but state encryption is off (Settings)".to_string(),
        ));
    }
    if s.state_encryption && tool == Tool::Terraform {
        out.push(diag(
            None,
            Severity::Warning,
            "state encryption needs OpenTofu: Terraform has no `encryption` block, so nothing is generated and the state stays unencrypted. Switch the tool to OpenTofu (Settings) to encrypt it".to_string(),
        ));
    }
    let plan = encryption_plan(layer, cat, provider, tool);
    if let Some(plan) = &plan {
        match (plan.source, key) {
            (KeySource::Passphrase, Some(k)) if layer.entity(k.id).is_none() => out.push(diag(
                Some(k.id),
                Severity::Info,
                format!(
                    "the state encryption key \"{}\" is not part of the {pname} layer, so the {pname} export encrypts its state with a passphrase (variable {PASSPHRASE_VAR})",
                    k.name
                ),
            )),
            (KeySource::Passphrase, Some(k)) => out.push(diag(
                Some(k.id),
                Severity::Info,
                format!(
                    "{pname} has no KMS key provider the export can use, so its state is encrypted with a passphrase (variable {PASSPHRASE_VAR}) rather than \"{}\". OpenTofu 1.10 had no Azure key provider; 1.12 has `azure_vault`, which the export does not use yet: the key would have to move to the bootstrap root together with its Key Vault",
                    k.name
                ),
            )),
            (KeySource::Passphrase, None) if matches!(provider, "aws" | "gcp") => out.push(diag(
                None,
                Severity::Info,
                format!(
                    "the state is encrypted with a passphrase (variable {PASSPHRASE_VAR}); choose an Encryption Key as the state encryption key (Settings) to use {} instead",
                    if provider == "aws" { "AWS KMS" } else { "Cloud KMS" }
                ),
            )),
            _ => {}
        }
        // A key other resources are encrypted with must be in their region.
        if let (KeySource::AwsKms, Some(k)) = (plan.source, &plan.key) {
            let bootstrap_region = plan.region.clone().unwrap_or_default();
            let main_region = aws_region(layer, cat);
            let used = layer.edges.iter().any(|e| &e.target == k);
            if used && !bootstrap_region.is_empty() && bootstrap_region != main_region {
                out.push(diag(
                    Some(k),
                    Severity::Warning,
                    format!(
                        "the bootstrap root creates this key in {bootstrap_region} (the S3 backend's region), but the resources encrypted with it are in {main_region}: KMS keys are regional, so they cannot use it. Keep the state bucket in {main_region}, or choose another key for the state"
                    ),
                ));
            }
        }
    }

    // What the bootstrap roots would refuse, reported here so the export's own gate
    // stops before writing half a configuration.
    for root in bootstrap_roots(layer, cat, provider, tool) {
        for d in crate::diagnostics::run(&root.project, cat, &root.provider) {
            if d.severity != Severity::Error {
                continue;
            }
            // The key's own problems are already reported on the canvas.
            if root
                .key
                .as_deref()
                .is_some_and(|k| d.entity.as_deref() == Some(k))
            {
                continue;
            }
            out.push(diag(
                None,
                Severity::Error,
                format!(
                    "State bootstrap ({}/): {} (Settings ▸ State backend)",
                    root.dir, d.message
                ),
            ));
        }
    }

    // Secrets the configuration itself puts into the state.
    let encrypted = plan.is_some();
    for e in layer.entities() {
        if e.manual {
            continue;
        }
        let Some(def) = cat.resource(e.resource_type) else {
            continue;
        };
        let Some(m) = cat.mapping(e.resource_type, provider) else {
            continue;
        };
        let fields = def.fields.iter().chain(m.fields.iter());
        for f in fields.filter(|f| f.state_secret) {
            let on = e
                .field(&f.name)
                .or_else(|| e.provider_field(provider, &f.name))
                .and_then(|v| v.as_bool())
                .or_else(|| f.default_value().and_then(|v| v.as_bool()))
                .unwrap_or(false);
            if !on {
                continue;
            }
            let what = format!("\"{}\" has '{}' on", e.name, f.label());
            let msg = match (remote, encrypted) {
                (None, false) => format!(
                    "{what}: the generated value is stored in plain text in local state; configure a remote backend and state encryption (Settings)"
                ),
                (None, true) => format!(
                    "{what}: the generated value is stored in local state (encrypted); configure a remote backend (Settings) so the only copy is not on this machine"
                ),
                (Some(b), false) => format!(
                    "{what}: the generated value is stored in plain text in the remote state ({} backend); turn on state encryption (Settings{})",
                    b.backend_type,
                    if tool == Tool::Terraform { "; it needs OpenTofu" } else { "" }
                ),
                (Some(_), true) => continue,
            };
            out.push(diag(Some(e.id), Severity::Warning, msg));
        }
    }
    out
}
